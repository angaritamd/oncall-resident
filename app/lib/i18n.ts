/** 18 → "18 min", 95 → "1 h 35 min", 120 → "2 h" */
export function fmtWait(m: number) {
  if (m < 60) return `${m} min`;
  const h = Math.floor(m / 60);
  const r = m % 60;
  return r ? `${h} h ${r} min` : `${h} h`;
}

